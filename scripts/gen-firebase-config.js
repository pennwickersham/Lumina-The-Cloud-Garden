#!/usr/bin/env node
/* Generates www/firebase-config.js from a native Firebase config file.
   Resolution order: android/app/google-services.json, then
   ios/App/App/GoogleService-Info.plist. Falls back to a placeholder
   (Firestore silently disabled) when neither file is present.

   Outputs only the fields the web Firestore SDK needs; appId is
   per-platform and unused, so it is intentionally omitted.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "www", "firebase-config.js");

const CANDIDATES = [
  {
    file: path.join(ROOT, "android", "app", "google-services.json"),
    load() {
      const j = JSON.parse(fs.readFileSync(this.file, "utf8"));
      const client = Array.isArray(j.client) ? j.client[0] || {} : {};
      const apiKey = client.api_key && client.api_key[0] && client.api_key[0].current_key;
      return {
        apiKey,
        projectId: j.project_info && j.project_info.project_id,
        storageBucket: j.project_info && j.project_info.storage_bucket,
        messagingSenderId: j.project_info && j.project_info.project_number,
      };
    },
  },
  {
    file: path.join(ROOT, "ios", "App", "App", "GoogleService-Info.plist"),
    load() {
      const out = execFileSync("/usr/bin/plutil", ["-convert", "json", "-o", "-", this.file], { encoding: "utf8" });
      const p = JSON.parse(out);
      return {
        apiKey: p.API_KEY,
        projectId: p.PROJECT_ID,
        storageBucket: p.STORAGE_BUCKET,
        messagingSenderId: p.GCM_SENDER_ID,
      };
    },
  },
];

function placeholders() {
  return {
    apiKey: "YOUR_API_KEY",
    projectId: "YOUR_PROJECT_ID",
    storageBucket: "YOUR_PROJECT_ID.appspot.com",
    messagingSenderId: "YOUR_SENDER_ID",
  };
}

function main() {
  const src = CANDIDATES.find((c) => fs.existsSync(c.file));
  const vals = src ? src.load() : placeholders();
  const authDomain = `${vals.projectId || "YOUR_PROJECT_ID"}.firebaseapp.com`;
  const generated = src ? `${path.relative(ROOT, src.file)} (${src.load === CANDIDATES[0].load ? "Android" : "iOS"})` : "no native config file found";
  const srcFile = src ? path.relative(ROOT, src.file) : "none";

  const body = `// Generated by scripts/gen-firebase-config.js — DO NOT HAND-EDIT.
// Rerun \`npm run sync\` to regenerate from ${srcFile}.
// Source: ${generated}${src ? "" : " — using placeholder values; Firestore stays disabled."}
window.firebaseConfig = {
  apiKey: ${JSON.stringify(vals.apiKey || "YOUR_API_KEY")},
  authDomain: ${JSON.stringify(authDomain)},
  projectId: ${JSON.stringify(vals.projectId || "YOUR_PROJECT_ID")},
  storageBucket: ${JSON.stringify(vals.storageBucket || "YOUR_PROJECT_ID.appspot.com")},
  messagingSenderId: ${JSON.stringify(vals.messagingSenderId || "YOUR_SENDER_ID")}
};
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  const key = vals.apiKey;
  console.log(`gen-firebase-config: ${src ? "wrote " + path.relative(ROOT, OUT) + " from " + path.relative(ROOT, src.file) : "NO CONFIG FOUND — wrote placeholder " + path.relative(ROOT, OUT)}`);
  if (src && !key) console.warn("  warning: apiKey missing from source file");
}

main();